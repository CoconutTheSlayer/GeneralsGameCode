"""Legacy stock-rig diagnostic that exposed detached rigid limbs.
Current articulated.py exports its own attached idle/run/fire pose previews.
Uses exported bone attachments and saved baked meshes; no runtime writes or portraits.
"""
import sys,json,struct,re
from pathlib import Path
import bpy
from mathutils import Vector
HERE=Path(__file__).resolve().parent;sys.path.insert(0,str(HERE))
from infantry import Infantry,chunks,cstr,BUILD,OUT,render

def review(name):
 meta=json.loads((BUILD/(name+'.json')).read_text())
 if not meta.get('external_skeleton'):
  print(name,'already uses original articulated rig; previews generated by articulated.py')
  return {'model':name,'review':'articulated.py generated idle/run/fire previews','poses':[]}
 bpy.ops.wm.open_mainfile(filepath=str(BUILD/(name+'.blend')))
 for obj in list(bpy.data.objects):
  if obj.type in ('LIGHT','CAMERA'):bpy.data.objects.remove(obj,do_unlink=True)
 rig=Infantry(name,'review','AmericaInfantryRanger');refs=[]
 for c,b,_ in chunks((OUT/(name+'.w3d')).read_bytes()):
  if c==0x700:
   for cc,bb,_ in chunks(b):
    if cc==0x702:
     for d,x,_ in chunks(bb):
      if d==0x704:refs.append((struct.unpack_from('<I',x)[0],cstr(x[4:]).split('.',1)[1]))
 parts=[]
 for idx,mesh in refs:
  obj=bpy.data.objects.get(mesh)
  if obj is None:
   numbered=re.match(r'^(.*?)(\d+)$',mesh)
   if numbered:obj=bpy.data.objects.get(numbered[1]+'.'+numbered[2].zfill(3))
  assert obj is not None,(name,mesh,list(bpy.data.objects.keys()))
  parts.append((mesh,rig.rig[idx][0],obj,'','solid'))
 for mat in bpy.data.materials:
  if mat.use_nodes:
   node=mat.node_tree.nodes.get('Principled BSDF')
   if node:node.inputs['Roughness'].default_value=.95
 render(name,parts)
 bpy.ops.wm.save_as_mainfile(filepath=str(BUILD/(name+'.blend')))
 for obj in list(bpy.data.objects):
  if obj.type in ('LIGHT','CAMERA'):bpy.data.objects.remove(obj,do_unlink=True)
 results=[]
 for label,anim,frame in [('idle','AIRNGR_STA',30),('running','AIRNGR_RNA',12),('firing','AIRNGR_ATA',2)]:
  world=rig.posed_world(anim,frame)
  for _,b,o,_,_ in parts:o.matrix_world=world[b]
  bpy.context.view_layer.update()
  render(name+'_'+label,parts)
  points=[o.matrix_world@Vector(p) for _,_,o,_,_ in parts for p in o.bound_box]
  results.append({'pose':label,'animation':anim,'frame':frame,'dimensions':[max(v[i] for v in points)-min(v[i] for v in points) for i in range(3)],'attachments':len(parts)})
  for obj in list(bpy.data.objects):
   if obj.type in ('LIGHT','CAMERA'):bpy.data.objects.remove(obj,do_unlink=True)
 return {'model':name,'poses':results}
if __name__=='__main__':
 names=sys.argv[sys.argv.index('--')+1:] if '--' in sys.argv else ['RURIFLE','RUKORNET','RUCMDO']
 results=[review(n) for n in names]
 (BUILD/'infantry-animation-review.json').write_text(json.dumps(results,indent=2)+'\n')
